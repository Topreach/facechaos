"""Generate Android resources and exact source-label lookups from reviewed source data."""
from pathlib import Path
import html
import json
import re

root = Path(__file__).resolve().parents[1]
data = json.loads((root / "localization/ui.json").read_text(encoding="utf-8"))
for values in data.values():
    expected = sorted(re.findall(r"%[0-9]+\$[ds]", values[0]))
    assert all(sorted(re.findall(r"%[0-9]+\$[ds]", text)) == expected for text in values), "Mismatched formatting arguments"
assert all(len(values) == 5 and all(values) for values in data.values())
assert len({values[0] for values in data.values()}) == len(data), "Duplicate English source label"
for index, language in enumerate(("en", "ar", "fr", "es", "pt")):
    folder = root / "app/src/main/res" / ("values" if language == "en" else "values-" + language)
    folder.mkdir(exist_ok=True)
    lines = ['<?xml version="1.0" encoding="utf-8"?>', '<resources>']
    for key, values in data.items():
        value = html.escape(values[index], quote=False).replace("'", "\\'").replace('"', '\\"')
        lines.append(f'    <string name="fc_{key}">{value}</string>')
    (folder / "strings.xml").write_text("\n".join(lines + ["</resources>", ""]), encoding="utf-8")
lookup = "\n".join('  case ' + json.dumps(values[0], ensure_ascii=True) + ':return c.getString(R.string.fc_' + key + ');' for key, values in data.items())
briefs = ','.join('R.string.fc_brief' + str(i) for i in range(15))
source = '''package com.facechaos.mobile;
import android.content.Context;
/** Generated by localization/generate.py. Resources remain the translation source. */
final class AppText {
 static boolean english(Context c){return c.getResources().getConfiguration().getLocales().get(0).getLanguage().equals("en");}
 static String t(Context c,String source){switch(source){
LOOKUP
 default:return source;}}
 static String[] items(Context c,String[] source){String[] result=source.clone();for(int i=0;i<result.length;i++)result[i]=t(c,result[i]);return result;}
 static String brief(Context c,int mode){int[] ids={BRIEFS};return c.getString(ids[mode]);}
 static String shortBrief(Context c,int mode){String text=brief(c,mode);int stop=text.indexOf('.');return stop<0?text:text.substring(0,stop+1);}
 static String summary(Context c,MiniGame g){return c.getString(R.string.fc_stage_summary,g.stage,g.paceLabel(),g.mode==3?g.voiceTarget():g.mode==1||g.mode==4?g.timedTarget():g.goal());}
}
'''.replace('LOOKUP', lookup).replace('BRIEFS', briefs)
(root / 'app/src/main/java/com/facechaos/mobile/AppText.java').write_text(source, encoding='utf-8')
print(f"Generated {len(data)} strings in five languages, including all 15 game briefs")
